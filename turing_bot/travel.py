def _norm(text):
    return " ".join(unicodedata.normalize("NFC", text).casefold().replace("ё", "е").split())


def answer(question):
    norm = _norm(question)
    packing = re.search(r"\bчто (?:взять|надеть|брать)(?: с собой)? (?:в|на) ", norm)
    sights = re.search(r"\b(?:куда (?:сходить|пойти|съездить)|что (?:посмотреть|посетить)|чем заняться|какие места)\b", norm)
    if len(norm) > 400 or not (ARRIVE.search(norm) or packing or sights) or not (ASK.search(norm) or sights) or REJECT.search(norm):
        return None
    city = next((data for data in CITIES.values() if re.search(r"\b(?:" + data["pattern"] + r")\b", norm)), None)
    season = next((name for name, expr in SEASONS if expr.search(norm)), None)
    if city is None and season is None:
        return None
    # A city alone is not enough: the question must be about arriving there.
    if city is None and not re.search(r"\b(?:город|страну|стран[еу]|столиц\w*|в [а-яе-]+(?:у|ь|ск|ы|и)\b)", norm):
        return None
    if city is CITIES["astana"] and re.search(r"\b(?:трц|торгов\w* центр\w*|надоел\w*)", norm):
        return "Тогда на набережную Есиля, в Ботанический сад или в Национальный музей. А зимой — на каток в Центральном парке."
    data = city or GENERIC
    if sights and city is None:
        return None
    parts = [data[season]] if season else []
    parts.insert(0, data["place"]) if sights else parts.append(data["place"])
    if season == "winter" and city and city.get("warm"):
        parts.append(city["warm"])
    text = " ".join(parts)
    while len(text) > 300 and len(parts) > 1:
        parts.pop()
        text = " ".join(parts)
    return text
