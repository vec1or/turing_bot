LIGHT = STOP | set("одно один одну всех лишь лучше посоветуй расскажи назови объясни думать думаешь хотел хотелось считается способ человек люди какой почему спасибо такое всего часто иногда обычно именно например первый однажды сейчас тебя можно мысли когда пример который очень стал однажды которое будет было вещи сразу вообще только просто свой свойство момент сказал делал сделал себя тебя сделать всего этого надо стоит делать слово".split())


def stems(text):
    result=[]
    for term in re.findall("[а-я]+",text.casefold().replace("ё","е")):
        if len(term)<3 or term in LIGHT:
            continue
        term=re.sub(r"(?:иями|ами|ями|ого|его|ому|ему|ыми|ими|ая|ое|ые|ий|ый|ой|ую|ах|ях|ом|ем|ов|ев|ою|ею|[аяеиуыью])$","",term)
        if len(term)>=3:
            result.append(term[:6])
    return result


class Associations:
    def __init__(self, directory=None):
        path=(Path(directory) if directory else Path(__file__).with_name("assets"))/"scene-words.json.gz"
        with gzip.open(path,"rt",encoding="utf-8") as f:
            self.weights=json.load(f)["weights"]
        self.seeds={key:set(stems(frame[0])) for key,frame in FRAMES.items()}

    def answer(self,text):
        q=text.casefold().replace("ё","е")
        if re.search(r"\b(?:сколько|кто|когда роди|который из|какого цвета|докажи|точн\w*|рифм\w*|три|две|пару|одним словом|объявление|загадк\w*)\b|\bили\b|\d",q):
            return None
        why=re.search(r"\b(?:почему|за что|чем тебе|что тебе дает)\b",q)
        personal=re.search(r"\b(?:тебе|твой|тебя|ты|тво[ияе]|любишь|любим\w*|нравится|предпочитаешь|запомнил\w*|по-твоему)\b",q)
        advice=re.search(r"\b(?:посовет\w*|порекоменд\w*|с чего начать|как (?:мне |нам |же |лучше )?(?:начать|организовать|подойти|подготов\w*|научи\w*|спланир\w*|улучш\w*|выбрать|решить)|что (?:мне |нам )?(?:попробовать|делать|сделать))\b",q)
        if not (advice or personal) or re.search(r"\b(?:за ширмой|нейросеть|какого пола|кто ты|переведи|сочини|придумай)\b",q):
            return None
        # Some narrower contexts have a materially different affordance: looking
        # out of a train window is possible, taking a walk aboard a bus is not.
        facets = (
            (r"электричк|вагон|поездом|в поезде", "Мне нравится смотреть в окно и ловить момент, когда город кончается, а поля уже начались.", "Я бы заранее проверил остановку, подготовил билет и сел так, чтобы видеть названия станций."),
            (r"марафон|забег|бегун|пробежк", "Мне приятнее бежать без гонки за временем и замечать, что знакомый подъём понемногу даётся легче.", "Я бы начал с короткой посильной дистанции, чередовал ходьбу с бегом и прибавлял нагрузку постепенно."),
            (r"библиотек|читальн", "Люблю библиотеку за возможность взять с полки совершенно незнакомую книгу, полистать и читать дальше только если зацепила.", "Я бы поискал одну знакомую книгу и посмотрел, что стоит рядом с ней на полке."),
            (r"репетиц", "Мне нравится сначала пройти всё целиком, а потом отдельно вернуться к тому месту, где мы сбились.", "Я бы засёк время, сделал один полный прогон и только после него стал разбирать слабые места."),
            (r"концерт|вживую|на сцене", "Мне нравится секунда, когда музыканты замолкают, а зал ещё не решился хлопать.", "Я бы выбрал место, откуда видно сцену, и пришёл чуть раньше начала."),
            (r"акварел|наброс|портрет|пейзаж",FRAMES["craft"][1],FRAMES["craft"][2]),
            (r"осваива|разучива|изуча",FRAMES["learning"][1],FRAMES["learning"][2]),
        )
        for expression,observation,step in facets:
            if re.search(expression,q):
                return step if advice else observation
        cues=set(stems(q))
        if not cues:
            return None
        ranks=[]
        for domain,seed in self.seeds.items():
            direct=len(cues & seed)
            values=sorted((self.weights[domain].get(w,0.) for w in cues-seed),reverse=True)
            score=2.8*direct+sum(values[:3])
            if direct or sum(v>=.72 for v in values)>=2:
                ranks.append((score,domain))
        ranks.sort(reverse=True)
        if not ranks or ranks[0][0]<1.85 or len(ranks)>1 and ranks[0][0]-ranks[1][0]<.18:
            return None
        _,view,action,reason=FRAMES[ranks[0][1]]
        if advice:
            return action+" "+reason
        if why:
            return reason
        return view
