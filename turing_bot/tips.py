TIPS = tuple((re.compile(r"\b(?:" + topic + r")"), text) for topic, text in TIPS)


def answer(question):
    norm = " ".join(unicodedata.normalize("NFC", question).casefold().replace("ё", "е").split())
    if len(norm) > 300 or not ASK.search(norm):
        return None
    # Questions about other people's feelings or what to *say* belong elsewhere.
    if re.search(r"\b(?:что (?:бы )?(?:ты )?(?:скажешь|ответишь)|почему)\b", norm):
        return None
    for expr, text in TIPS:
        if expr.search(norm):
            return text
    return None
