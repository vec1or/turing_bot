def objects_in(q):
    tokens = words(q)
    return [row for row in OBJECTS if any(token.startswith(cue[:max(4,len(cue)-2)]) for cue in row[0].split() for token in tokens)]


def imagined_action(q):
    if not re.search(r"если (?:бы|б )|представь|вообрази|мог бы|оказал\w* бы|суперсил|сверхспособ", q):
        return None
    if not re.search(r"\b(?:ты|у тебя|тебе|твой|выбрал\w*|сделал\w*|поступил\w*|взял\w*|хотел\w*|сможешь|куда|как бы|на что потрат\w*)\b", q):
        return None
    if re.search(r"невидим|невидимк|незаметн", q):
        return "Пошёл бы на кафедру послушать, что преподы про нас говорят. А потом в кино без билета, грех не воспользоваться."
    if re.search(r"читат\w* мысли|слышат\w* мысли|чита\w* чужие мысли", q):
        return "Сначала выяснил бы, как это выключить. В переполненном автобусе я и обычные разговоры не всегда выдерживаю."
    if re.search(r"телепорт|мгновенно (?:попасть|оказаться|перенес)|перемещаться в пространстве", q):
        return "Позавтракал бы у моря и успел обратно к первой паре. Особенно нравится часть, где не надо вставать раньше ради дороги."
    if re.search(r"летать|полететь без|умел\w* лететь|появил\w* крылья", q):
        return "Для начала поднялся бы чуть выше крыши. Хочется наконец увидеть, куда за домами сворачивает дорога, по которой я каждый день хожу."
    if re.search(r"животн.{0,22}(?:язык|говор)|понимать (?:речь )?(?:кошек|собак|зверей|животных)|разговаривать с животн", q):
        return "Присел бы рядом с дворовым котом и дал ему выговориться. Давно интересно, из-за чего он каждое утро спорит с закрытой дверью."
    if re.search(r"прошл\w*|верну\w* во времен|времени назад", q) and not re.search(r"книг|итог|экзамен|ошиб", q):
        return "Зашёл бы на кухню в детстве, пока чайник закипает и все ещё дома. Посидел бы с ними, не поглядывая на часы."
    if re.search(r"суперсил|сверхспособ", q) and not re.search(r"\bили\b|три |две ", q):
        return "Телепортацию. Утром успевал бы на пару, а вечером мог бы зайти на чай к человеку, до которого сейчас полдня ехать."
    return None


def features(token):
    # Shared prefixes handle endings. Trigrams let similar stems contribute.
    letters = "^" + token
    return {token[:5], *(letters[i:i+3] for i in range(len(letters)-2))}


class Imagination:
    def __init__(self):
        self.vectors = []
        document_frequency = Counter()
        for scene in SCENES:
            vector = Counter(f for cue in words(scene.cues) for f in features(cue))
            self.vectors.append(vector)
            document_frequency.update(vector.keys())
        self.idf = {f: math.log((len(SCENES)+1)/(n+1))+1 for f,n in document_frequency.items()}

    def scene(self, tokens):
        scores = [0.] * len(SCENES)
        for token in tokens:
            if len(token) < 3:
                continue
            signature = features(token)
            weights = sum(self.idf.get(f, 3.6) for f in signature)
            for i, vector in enumerate(self.vectors):
                coverage = sum(self.idf[f] for f in signature if f in vector) / weights
                if coverage >= .58:
                    scores[i] += coverage ** 3
        return SCENES[max(range(len(scores)), key=scores.__getitem__)] if max(scores) >= .28 else None

    def answer(self, question):
        q = question.casefold().replace("ё","е")
        objects = objects_in(q)
        speaking = re.search(r"что.{0,35}(?:сказа|ответи|ворча|попроси|напиш|написа|прошеп)|(?:перв\w*|какую) (?:бы )?(?:фраз|реплик)|на что.{0,12}пожалова", q)
        if len(objects) == 1 and speaking and re.search(r"если|заговор|представ|вообраз|ожи[вл]|что бы", q):
            return "«" + objects[0][1].rstrip(".") + "»."
        if len(objects) == 1 and re.search(r"прода[йж]|реклам|слоган", q):
            broken = re.search(r"дыряв|продыряв|сломан|разбит|нерабоч|порван", q)
            if broken:
                return "Зато с его помощью можно " + objects[0][3] + "."
            return objects[0][2] + "!"
        magical = imagined_action(q)
        if magical:
            return magical
        # A tiny writing task can carry invented words verbatim. Quoted text
        # goes into direct speech or an inscription so its case stays valid.
        story = re.search(r"(?:сочини|расскажи|придумай|напиши|составь).{0,48}(?:истори|рассказ|сказк|предложени)", q)
        if story:
            names = re.findall(r'[«„“"]([^«»„“”"!?\n]{1,40})[»“”"]', question)
            if not names:
                listed = re.search(r"\b(?:со словами|слова(?:ми)?)\s*[:—]\s*(.+)", q)
                if listed:
                    names = [s.strip(" .") for s in re.split(r",\s*|\s+и\s+", listed[1])]
            if 1 <= len(names) <= 3 and all(re.fullmatch(r"[А-Яа-яЁё -]{1,32}", s) for s in names):
                one = bool(re.search(r"одн(?:им|о|ом) предложени", q))
                label = " / ".join(names)
                if one:
                    return f"На коробке было написано «{label}», а внутри лежал ключ от нашего старого дома."
                if len(names) == 3:
                    return f"Первой подсказкой было слово «{names[0]}». За ним на карте проступило «{names[1]}», а там, где мы стояли, кто-то уже нацарапал «{names[2]}»."
                return f"Мне подсунули конверт с надписью «{label}». Внутри лежало фото моей комнаты, сделанное завтра утром."
        if re.search(r"(?:придумай|подбери|назови|какая|зарифмуй).{0,28}рифм|зарифмуй", q):
            target = re.search(r'(?:к слову|со словом|на слово|зарифмуй(?: слово)?)\s+[«"]?([а-я-]{2,30})', q)
            if target:
                # Stress and endings in these small rhyme families are known.
                for family in ("окно кино зерно вино", "вода звезда беда среда", "кот полет лед мед",
                               "чай невзначай встречай выручай", "день тень лень ступень", "луна весна струна волна",
                               "свет билет рассвет ответ", "мечта высота красота", "ночь дочь прочь",
                               "утро мудро", "рука река строка облака", "огонь ладонь гармонь",
                               "мороз вопрос паровоз", "тишина глубина старина", "друг круг вдруг"):
                    options = family.split()
                    if target[1] in options:
                        other = next(w for w in reversed(options) if w != target[1])
                        return other.capitalize() + "."
        metaphor = re.search(r"метафор|сравнени|сравни |на что похож|каков[оа] на вкус|какой на вкус|какого (?:бы )?цвета|если бы|если б |представь|вообрази|мог\w* (?:бы )?(?:говорить|заговорить)|был\w* бы|чем пахн|как звуч", q)
        naming = re.search(r"придум\w*|дай |подбери|как (?:бы ты |ты бы )?назва|как назвать", q) and re.search(r"назва|имя\b|кличк|прозвищ", q)
        if not (metaphor or naming):
            return None
        tokens = words(q)
        scene = self.scene(tokens)
        if naming and not re.search(r"причин|пример|недостат|достоин|столиц|учен|автор|три |дв[ае] ", q):
            if scene:
                return scene.name + "."
            return None
        if not scene:
            return None
        # A literal question about an observable property needs evidence.
        explicit = re.search(r"если|представ|метафор|по-твоему|ассоци|настроен|каким бы|какой бы|мог\w* бы", q)
        abstract = re.search(r"понедельник|вторник|сред[ау]|четверг|пятниц|суббот|воскресень|утро|детств|тишин|одиночеств|счасть|тревог|экзамен|свобод|радост|груст|врем[яе]|осен|памят|воспоминан", q)
        if not (explicit or abstract or re.search(r"сравн|на что похож", q)):
            return None
        short = re.search(r"одн(?:им|о) слов", q)
        if re.search(r"запах|пахн|пахло|аромат", q):
            return (scene.scent.split()[-1] if short else scene.scent).capitalize() + "."
        if re.search(r"звуч|звук|как\w* (?:бы )?голос", q):
            return (scene.sound.split()[0] if short else scene.sound).capitalize() + "."
        if re.search(r"цвет|оттен", q):
            return scene.colour.capitalize() + "." if short else f"Мне видится {scene.colour}. Первое, что всплыло в голове, — {scene.comparison}."
        if re.search(r"вкус", q):
            return scene.taste.capitalize() + "."
        if re.search(r"что.{0,32}(?:сказа|шепну|ворча|жалов|прошеп|произнес|попрос|написа)|какую фразу|первая фраза", q):
            return "«" + scene.voice + "»"
        if re.search(r"сравнен|метафор|сравни |на что похож", q):
            return "Для меня это как " + scene.comparison + "."
        return None
