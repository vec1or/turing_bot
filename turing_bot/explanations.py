def matches(stems, tokens):
    return any(t.startswith(stem) for stem in stems.split() for t in tokens)


def explain(text):
    q = text.casefold().replace("ё","е")
    if re.search(r"\b(?:если бы|представь|докажи|опровергни|сколько|две причины|три причины|четыре причины)\b", q):
        return None
    concept = re.search(r"\b(?:что (?:такое|значит|означает)|что для тебя|как ты понимаешь(?: слово)?|объясни(?: слово| смысл слова)?)\s+[«\"]?(?:для тебя |настоящая |настоящее |настоящий )?([а-я-]+)", q)
    if concept:
        subject = concept[1]
        tail = q[concept.end():].split("?")[0].strip(' .!»,–—"')
        if not tail or tail in {"для тебя","простыми словами","по-твоему","своими словами","в двух словах"}:
            for label, meaning, illustration in VALUES:
                if subject == label:
                    return "Для меня " + label + " — это " + meaning + ". " + illustration
    simple = re.fullmatch(r"(?:а |объясни[, ]+)?(?:что (?:такое|значит)|что за)\s+([а-я]+)[?!. ]*", q)
    if simple and simple[1] in DEFINITIONS:
        row = MECHANISMS[DEFINITIONS[simple[1]]]
        return row[2] + " " + row[3]
    if not re.search(r"\b(?:почему|зачем|отчего|из-за чего|как (?:работает|получается)|объясни)\b", q):
        return None
    tokens = re.findall(r"[а-я]+", q)
    found = [row for row in MECHANISMS if matches(row[0], tokens) and matches(row[1], tokens)]
    # «Почему небо голубое, а на закате красное?» names two effects at once.
    if len(found) >= 2 and re.search(r",\s*а\s|\sи\s(?:почему|зачем)", q):
        for both in (found[0][2] + " А " + found[1][2][:1].lower() + found[1][2][1:] + " " + found[1][3], found[0][2] + " " + found[1][2]):
            if len(both) <= 300:
                return both
    for idx, (subject, effect, mechanism, illustration) in enumerate(MECHANISMS):
        if not (matches(subject, tokens) and matches(effect,tokens)):
            continue
        if idx == 0:
            if not matches("ветр ветер сквозня", tokens):
                return mechanism + " От тепла и сухого воздуха это обычно происходит быстрее."
        if idx == 5 and "эхо" not in tokens and not matches("отраж", tokens):
            continue
        return mechanism + " " + illustration
    return None
