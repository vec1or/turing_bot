    @staticmethod
    def _word_arithmetic(norm):
        numbers = {"ноль": 0, "один": 1, "одна": 1, "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6,
                   "семь": 7, "восемь": 8, "девять": 9, "десять": 10, "сто": 100}
        ops = {"плюс": "+", "минус": "-", "умножить на": "*", "разделить на": "/", "поделить на": "/"}
        text = norm.replace("×", "*").replace("х", "*") if re.search(r"\d\s*[х×]\s*\d", norm) else norm
        body = re.sub(r"^(?:а |ну |слушай,? )?(?:сколько (?:будет|получится)|посчитай|реши|вычисли)\s*", "", text).strip(" ?!.:")
        for word, op in ops.items():
            body = body.replace(word, f" {op} ")
        tokens = body.split()
        expr = []
        for t in tokens:
            if t in numbers:
                expr.append(str(numbers[t]))
            elif re.fullmatch(r"\d{1,4}|[-+*/()]", t):
                expr.append(t)
            else:
                return None
        if len(expr) < 5 or not any(o in expr for o in "+-") or not any(o in expr for o in "*/"):
            return None
        import ast
        try:
            value = eval(compile(ast.parse(" ".join(expr), mode="eval"), "<expr>", "eval"), {"__builtins__": {}}, {})
        except Exception:
            return None
        value = int(value) if float(value).is_integer() else round(value, 2)
        return f"{value}. Сначала умножение, классическая ловушка."

    @staticmethod
    def _mental_math(norm):
        found = re.search(r"(\d{1,4})\s*(?:умножить на|умноженное на|на|\*|x|х|×)\s*(\d{1,4})", norm)
        if not found or not re.search(r"\b(?:умнож\w*|посчитай|сколько|в уме)\b", norm):
            return None
        a, b = int(found[1]), int(found[2])
        if not re.search(r"умнож|\*|×| x | х ", norm) and "сколько будет" not in norm:
            return None
        result = a * b
        if a * b >= 10000:
            from .rounds import rough
            return rough(a * b)
        if re.search(r"\b(?:как (?:ты )?(?:считал|посчитал)|объясни|распиши|покажи)\b", norm) and b >= 10:
            tens, ones = b // 10 * 10, b % 10
            return (f"{result}. Сначала {a} на {tens} — это {a * tens}, потом {a} на {ones} — {a * ones}, "
                    f"сложил и получил {result}.")
        return f"{result}, если в уме не ошибся."

