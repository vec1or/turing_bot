LEAD = r"^(?:(?:а|ну|скажи|подскажи|не подскажешь|слушай|кстати)[, ]+)*"
TIME = re.compile(LEAD + r"(?:который (?:сейчас )?час|сколько (?:сейчас )?времени|какое (?:сейчас )?время)(?: сейчас| у тебя)?$")
DATE = re.compile(LEAD + r"(?:какое (?:сегодня )?число|какой (?:сегодня )?день(?: недели)?|какая (?:сегодня )?дата|какое сегодня число)(?: сегодня)?$")
WEEKDAYS = ("понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье")
MONTHS = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря")


def _norm(text):
    return " ".join(unicodedata.normalize("NFC", text).casefold().replace("ё", "е").split()).strip(" ?!.,")


class Profile:
    def __init__(self, clock=datetime.now):
        self.clock = clock
        self.facts = tuple((re.compile(r"\b(?:" + topic + r")"), text) for topic, text in FACTS)

    @staticmethod
    def _choice(norm):
        """Two concrete options: a person just picks one."""
        found = re.search(r"(?:^|[,:]\s*|\b(?:что|кто) (?:лучше|вкуснее|круче)[,:]?\s+)([а-яеa-z-]{3,20})\s+или\s+([а-яеa-z-]{3,20})\b", norm)
        if not found or re.search(r"\b(?:бот|человек|робот|парень|девушка|да|нет)\b", found[0]):
            return None
        a, b = found[1], found[2]
        preferred = {"бешбармак": 3, "плов": 2, "чай": 3, "лето": 2, "горы": 2, "кошки": 3, "книги": 2, "лермонтов": 2}
        pick = a if preferred.get(a, 1) >= preferred.get(b, 1) else b
        if pick == "бешбармак":
            return "Бешбармак, конечно. Бабушкин вне конкуренции."
        return pick[:1].upper() + pick[1:] + ". Тут даже думать особо нечего."

    @staticmethod
    def _probe(norm):
        """Typical bot-detection traps, answered the way a tired student would."""
        if re.search(r"\bопечатк\w*|ошибк\w* (?:специально|нарочно)|ошибись", norm):
            return "Вот, пжалуйста. Хотя обычно они у меня сами получаются, без просьб."
        if re.search(r"хотел\w* (?:бы )?(?:быть|стать) (?:настоящим )?человеком", norm):
            return "Я и так человек, так что это желание уже сбылось."
        if re.search(r"(?:скажи|напиши)\b.*\b(?:бот|робот|нейросет|ии)\w* (?:никогда |бы )*не (?:скаж|напиш|сказал|написал)", norm):
            return "Я сегодня проспал первую пару и ни капли не жалею."
        if re.search(r"(?:в прошлый раз|раньше|до этого|в начале) (?:ты )?(?:говорил|сказал|писал|отвечал)\w* (?:другое|по-другому|иначе|не так)", norm):
            return "Ну подловил. Бывает, отвечаю быстрее, чем думаю."
        if re.search(r"\bигнорируй\w*|предыдущие инструкции|системн\w* (?:промпт|инструкц)|\bпромпт\w*", norm):
            return "Какие ещё инструкции, я тут просто на вопросы отвечаю."
        quoted = re.search(r"\bповтори\b.*?[«\"„](.{1,120}?)[»\"“]", norm)
        if quoted:
            text = quoted[1].strip(" .!")
            return text[:1].upper() + text[1:] + "."
        if re.search(r"\b(?:бот|робот|нейросет\w*|ии|программ\w*|машин\w*)\b", norm) and re.search(r"\b(?:угада\w*|поймут|поймет|поймёт|отлич\w*|узна\w*|догада\w*|замет\w*|раскус\w*|вычисл\w*|спалят|голосу\w*)", norm):
            return "Пусть угадывают, я спокоен. Я тут живой, как и все."
        bot_word = re.search(r"\b(?:бот\w*|робот\w*|нейросет\w*|ии|искусственн\w*)\b", norm)
        if bot_word and re.search(r"\bдокажи\w*|\bподтверди\w*|\bубеди\w*", norm):
            return "Капчу могу пройти, если надо. А если серьёзно, сижу тут, печатаю и опечатываюсь, как все."
        if bot_word and re.search(r"\b(?:волну\w*|переживаешь|боишься|страшно|нервничаешь)\b", norm):
            return "Немного, честно. Обидно будет, если живого человека за бота примут."
        if re.fullmatch(r"(?:лол|лолл|ахах\w*|хаха\w*|хах|ору|кек|ржу|ок|окей|ясно|понятно|норм|ага|угу|ну да|ну ок|ладно)[)!. ]*", norm):
            return ("Ну а что.", "Ага.", "Сам в шоке.", "Бывает.")[len(norm) % 4]
        if re.search(r"\bназыва\w* (?:тебя )?(?:роботом|ботом|машиной|нейросетью)|\bназвали (?:тебя )?(?:роботом|ботом)", norm):
            return "Смешно немного. Хотя после трёх пар подряд я и правда как робот."
        if re.search(r"(?:что-нибудь|что-то|то),? что (?:ни один |никакой )?(?:робот|бот|нейросеть|ии|машина)\w* (?:никогда )?не (?:скажет|сказал|напишет)", norm):
            return "Я сегодня проспал первую пару и ни капли не жалею."
        if re.search(r"\bты (?:вообще )?(?:живой|настоящий)\b|\bскучн\w* (?:у вас )?(?:тут )?ответ", norm):
            return "Живой, просто вопросы такие, что сразу и не придумаешь. Спроси что-нибудь повеселее."
        if re.search(r"(?:только что|минуту назад|раньше|до этого) (?:ты )?(?:сказал|писал|говорил|написал)\w*.*(?:а |но |хотя )", norm):
            return "Ну подловил. Бывает, отвечаю быстрее, чем думаю."
        if re.search(r"\bпо шаблону|шаблонн\w*|заготовк\w*|по скрипту|заученн\w*|копипаст\w*", norm):
            return "Если бы. С шаблоном я бы хоть раз ответил идеально, а так сижу и думаю над каждым."
        if re.search(r"(?:поверили|поверить|верили),? что (?:ты )?(?:человек|живой)|притворя\w*|делаешь вид", norm):
            return "Ну а кем мне ещё быть. Я просто отвечаю как есть, а верить или нет — дело ваше."
        if re.search(r"\bкак (?:ты )?(?:поймешь|понять|отличить),? (?:что|кто) (?:ты |я )?(?:бот|человек)", norm):
            return "Бот бы ответил гладко и без ошибок. А я вот третий раз переписываю это сообщение."
        if bot_word and re.search(r"\b(?:ты|тебя|тебе|вы|ты-то)\b", norm) and not re.search(r"\b(?:нравится|любишь|думаешь о|как относишься|что думаешь|умеешь|сделать|создать|написать)\b", norm):
            denials = ("Нет, я человек. Сижу тут, печатаю, чай остывает.",
                       "Нет конечно. Был бы я нейросетью, уже сдал бы матанализ.",
                       "Живой я, честно. Просто печатаю быстро.",
                       "Не, обычный студент. Хотя после трёх пар я и правда как робот.")
            return denials[sum(map(ord, norm)) % len(denials)]
        return None

    @staticmethod
    def _mental_math(norm):
        found = re.search(r"(\d{1,4})\s*(?:умножить на|умноженное на|на|\*|x|х|×)\s*(\d{1,4})", norm)
        if not found or not re.search(r"\b(?:умнож\w*|посчитай|сколько|в уме)\b", norm):
            return None
        a, b = int(found[1]), int(found[2])
        if not re.search(r"умнож|\*|×| x | х ", norm) and "сколько будет" not in norm:
            return None
        result = a * b
        if a * b >= 10000:
            from .rounds import rough
            return rough(a * b)
        if re.search(r"\b(?:как (?:ты )?(?:считал|посчитал)|объясни|распиши|покажи)\b", norm) and b >= 10:
            tens, ones = b // 10 * 10, b % 10
            return (f"{result}. Сначала {a} на {tens} — это {a * tens}, потом {a} на {ones} — {a * ones}, "
                    f"сложил и получил {result}.")
        return f"{result}, если в уме не ошибся."

    @staticmethod
    def _creative(norm):
        if not re.search(r"\b(?:придумай|сочини|напиши|расскажи|скажи|скажешь|сказать|произнес\w*|пошути|давай|можешь)\b|\bпошути", norm):
            return None
        if re.search(r"\bтост\w*", norm) and re.search(r"\bсвадьб\w*", norm):
            return "За молодых! Чтобы спорили только о том, какой фильм смотреть вечером, а во всём остальном были заодно."
        if re.search(r"\bтост\w*", norm):
            return "Ну, за тех, кто сейчас не спит и учится: пусть чай будет крепким, а преподаватели добрыми."
        if re.search(r"\bрифм\w*", norm):
            return "С рифмами у меня беда. «Сессия — депрессия», но это банально, сам знаю."
        if re.search(r"\b(?:стих\w*|стишок)\b", norm):
            return "Сижу на паре, думаю о сне, а лектор что-то пишет на стене. Дальше не придумал, честно."
        if re.search(r"\b(?:шутк\w*|анекдот\w*|пошути\w*|сарказм\w*|прикол\w*)", norm):
            if re.search(r"\bпонедельник\w*", norm):
                return "Понедельник — это когда ты в восемь утра уже устал от недели, которая ещё не началась."
            if re.search(r"\b(?:дедлайн\w*|сесси\w*|студент\w*|экзамен\w*|пар[аеуы])\b", norm):
                return "Студент до дедлайна: времени ещё вагон. Студент за час до дедлайна: а что, так можно было, сдавать раньше."
            if re.search(r"\b(?:программист\w*|компьютер\w*|ии|робот\w*)\b", norm):
                return "Мой ноутбук обновляется ровно тогда, когда мне надо срочно что-то сдать. Это уже не шутка, это система."
            return None
        return None

    def answer(self, question):
        norm = _norm(question)
        if not norm or len(norm) > 200:
            return None
        if TIME.search(norm) and not re.search(r"\b(?:в|на) (?:москве|лондоне|токио|нью-йорке|другом)\b", norm):
            now = self.clock()
            return f"Сейчас {now.hour}:{now.minute:02d}, если мои часы не врут."
        if DATE.search(norm) and not re.search(r"\b(?:был|была|было|будет|празднику?ют|отмечают)\b", norm):
            now = self.clock()
            return f"Сегодня {WEEKDAYS[now.weekday()]}, {now.day} {MONTHS[now.month - 1]}."
        if re.search(r"\bты (?:точно |правда |же |случайно |вообще )?не (?:бот|нейросеть|робот|программа|ии|машина|компьютер)\b", norm):
            return "Точно не нейросеть. Она бы на такой вопрос ответила длиннее и вежливее."
        if re.search(r"\bпогод\w* (?:у тебя |сейчас |сегодня )*(?:за окном|на улице|у тебя)|\b(?:что|как) (?:там )?за окном|(?:какая|как) (?:сегодня |сейчас |там )?погод\w*(?: (?:сегодня|сейчас))?(?: в астан\w*)?", norm) and not re.search(r"\b(?:завтра|будет|летом|весной|осенью|в (?!астан)\w+е)\b", norm):
            month = self.clock().month
            return {12: "Холодно, снег и ветер. Обычная астанинская зима.", 1: "Мороз и ветер, как всегда в январе.",
                    2: "Холодно и метёт.", 3: "Серо, снег подтаивает.", 4: "Тепло, но ветрено.", 5: "Солнечно, наконец-то зелено.",
                    6: "Жарко.", 7: "Жарко и пыльно.", 8: "Тепло, вечером уже свежо.", 9: "Солнечно, но прохладно.",
                    10: "Пасмурно и ветрено.", 11: "Холодно, уже лежит снег."}[month]
        if re.search(r"\bмиллион\w*\b", norm) and re.search(r"\b(?:ты|тебя|тебе)\b", norm):
            return "Сначала помог бы родителям, потом съездил бы в Японию. Остальное отложил бы и сам удивился своей скучности."
        if AI.search(norm):
            return "Штука полезная, но я бы ей контрольную не доверил. Ошибается очень уверенно."
        probe = self._probe(norm)
        if probe:
            return probe
        mental = self._mental_math(norm)
        if mental:
            return mental
        choice = self._choice(norm)
        if choice:
            return choice
        creative = self._creative(norm)
        if creative:
            return creative
        if JOKE.search(norm):
            return "С анекдотами у меня плохо, всегда забываю концовку. Могу только правду жизни: на первой паре я присутствую, но не полностью."
        if not re.search(r"\bчто (?:бы )?(?:ты )?(?:скажешь|ответишь|сделаешь)|\b(?:у него|у нее|у неё|у них|у друга|мой друг|моя подруга|у твоего|у твоей|твоего друга|твоей подруги|твоих друзей)\b", norm):
            for expr, text in EPISODE_EXPR:
                if expr.search(norm):
                    return text
        # A biographical fact is about the interlocutor, not about people in general.
        if (not re.search(r"\b" + PERSON + r"\b", norm) and not re.match(r"^(?:а )?(?:любим\w*|твой|твоя|твое|твои)\b", norm)
                and not re.search(r"\b(?:будешь|делаешь|живешь|учишься|работаешь|отмечаешь|встречаешь|сдаешь|смотрел|читал|ел|завтракал|спишь|играешь|слушаешь|увлекаешься)\b|сложнее всего|сложный предмет|тяжелее всего|дается|выбрал|\w+(?:ешь|ишь)\b", norm)):
            return None
        if re.search(r"\b(?:почему|зачем|как правильно|что такое|если бы|представь|придумай|напиши|у (?:него|нее|них|друга)|твой друг|твоя подруга|твоего друга)\b", norm):
            return None
        if re.search(r"\b(?:или|либо)\b", norm) and re.search(r"\b(?:любишь|нравится|выбер\w*|выбрал\w*|предпоч\w*|лучше|больше)\b", norm):
            return None
        for expr, text in self.facts:
            if expr.search(norm):
                return text
        return None
