    idiom=re.search(r"\b(?:есть|есть всего|осталось|всего|уложиться в|за) (полчаса|четверть часа|один час)\b",s)
    if clock or idiom:
        bound=clock or idiom
        before=re.split(r"[.!?;]",s[:bound.start()])[-1]
        other_goal=GOAL_HEAD.search(before)
        if other_goal and _norm(other_goal[1])!=_norm(phrase.split()[0]):
            return None
        word=clock[1] if clock else idiom[1]
        n=int(word) if word.isdigit() else {**MINUTES,"полчаса":30,"четверть часа":15,"один час":60}[word]
        if not 5<=n<=180:
            return None
        head=max(1,n//6)
        tail=max(1,n//5)
        return (f"Чтобы {phrase}, я бы распределил время так. {head} мин — {op.prepare}. "
                f"{n-head-tail} мин — {op.act}. {tail} мин — {op.verify}.")
    if LOW_BUDGET.search(s):
        verb=_norm(phrase.split()[0])
        if re.match(r"организова|устрои|провести|спланирова",verb):
            return f"Чтобы {phrase}, я бы начал с бесплатной части. Узнал бы, каким местом можно воспользоваться и что участники готовы принести. В список покупок попало бы только то, без чего встреча не состоится."
        if re.match(r"упакова|собра|уложи|перевез|изготови|смастери|сдела|нарисова",verb):
            return f"Чтобы {phrase}, я бы разложил всё, что уже есть, и собрал один пробный вариант. Тогда станет видно, что действительно придётся докупить, а что можно заменить или одолжить."
