def _norm(text):
    return unicodedata.normalize("NFC",text).casefold().replace("ё","е")


def _phrase(text, pattern, limit=58):
    found=re.search(pattern,text,re.I)
    if not found:
        return ""
    value=re.split(r"[,;.!?:]|\s+(?:а|но|потому|хотя|поэтому|ведь|чтобы)\s",found[1],maxsplit=1,flags=re.I)[0]
    value=value.strip(" «»\"—-")
    if not value or len(value)>limit or re.search(r"\b(?:ты|вы|почему|зачем|скажи|можешь)\b",value,re.I):
        return ""
    return value


def _quote(text):
    return "«"+text+"»"


def _specific_praise(text):
    # Preserve the source's verb agreement, including plural coordination.
    hit=re.search(r"\b(?:(?:мне|меня)\s+)?(?:особенно\s+|больше всего\s+)?(понравил(?:ся|ась|ось|ись)|нрав(?:ится|ятся)|запомнил(?:ся|ась|ось|ись)|впечатлил[аио]?)\s+",text,re.I)
    if not hit:
        return None
    detail=_phrase(text[hit.end():],r"^(.+)")
    if not detail or re.search(r"^(?:всё|все|это|он[аои]?|как)$",detail,re.I):
        return None
    intro=("Мне " if not hit[1].casefold().startswith("впечат") else "Меня ")
    intro+="особенно "+hit[1].casefold()+" "+detail+". "
    clue=_norm(detail)
    if re.search(r"тен[ьи]|освещ|свет|полутон",clue):
        emphasis="Из-за света и тени у меня появилось ощущение глубины."
    elif re.search(r"цвет|оттен|палитр|контраст",clue):
        emphasis="Сочетание цветов хочется рассмотреть подольше."
    elif re.search(r"ритм|звук|темп|переход",clue):
        emphasis="Я поймал себя на том, что хочу послушать этот момент ещё раз."
    elif re.search(r"финал|концов|последн|развяз",clue):
        emphasis="Именно об этом моменте я продолжал думать потом."
    else:
        emphasis="Вот эта деталь мне и запомнилась."
    return _quote(intro+emphasis)


def _achievement(text,s):
    work=WORK.search(s)
    if not work or not SUCCESS.search(s) or re.search(r"\b(?:двойк\w*|проигра\w*|не (?:смог\w*|успел\w*|удалось|получилось|справил\w*|выиграл\w*|горжусь|порадова\w*)|вряд ли)\b",s):
        return None
    if not (PRAISE.search(s) or re.search(r"\b(?:ура|радуюсь|радуемся|получилось|справился|справилась|я наконец|я впервые)\b",s)):
        return None
    # Indirect quotation preserves past tense and agreement as supplied.
    achievement=_phrase(text[work.start():], r"^(.+)")
    if not achievement:
        return None
    viewer=bool(re.search(r"\bя\s+(?:сам[а]?\s+|впервые\s+|наконец\s+)*(?:\w+\s+){0,2}$",s[:work.start()]))
    if not viewer and not RELATIVE.search(s[:work.start()]):
        return None
    if any(c in achievement for c in "?!"):
        return None
    if viewer:
        return "Поздравляю! Одно дело было задумать, а ты "+achievement+". Теперь есть результат, который можно показать."
    if re.search(r"\b(?:она|сестра|мама|подруга|дочь|бабушка)\b",s[:work.start()]):
        actor="она"
    elif re.search(r"\b(?:он|брат|папа|друг|сын|дедушка)\b",s[:work.start()]):
        actor="он"
    else:
        return None
    return f"Как здорово, что {actor} {achievement}! Особенно ценно, когда видишь, сколько старания близкий человек вложил в свою работу."


def _speech(text,s):
    if PRAISE.search(s):
        result=_specific_praise(text)
        if result:
            return result
    if SUCCESS.search(s) and RELATIVE.search(s) and not re.search(r"\bне (?:победил\w*|выиграл\w*|удалось|получил\w*)",s):
        if re.search(r"\b(?:выиграл\w*|победил\w*|первое место|призов\w* место)\b",s):
            return _quote("Поздравляю с победой! Я особенно рад за тебя. Расскажи потом, какой момент тебе больше всего запомнился.")
        if WORK.search(s) and re.search(r"\b(?:с первым|первая|первый|впервые|сама?\b|поздрав\w*)",s):
            return _quote("Поздравляю с результатом! Особенно здорово, что твоя задумка стала настоящей работой. Покажи её ещё раз, хочется рассмотреть детали.")
