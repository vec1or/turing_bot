UNIT=r"(?:руб(?:лей|ля|ль)?|тенге|₽|мин(?:ута|уту|уты|ут)?|балл(?:а|ов)?)"
CAP=re.compile(r"\b(?:лимит|бюджет|максимум|предел|в распоряжении|у меня|у нас|могу потратить|есть только|осталось)\s*(?:на [а-яё]+\s+)?(?:составляет\s+|всего\s+|только\s+|ровно\s+)?[—–:-]?\s*(\d{1,7})\s*("+UNIT+r")",re.I)
ITEM_COST=re.compile(r"(?:^|[.!?,;]\s*|\s+или\s+)(?:а\s+)?([а-яёa-z][а-яёa-z -]{0,46}?)\s+(?:стоит|обойд[её]тся в|стоят|занимает|занимают|потребует|потребуют|[—–-])\s*(\d{1,7})(?:\s*("+UNIT+r"))?(?=[\s.,;!?]|$)",re.I)
CHOOSE = re.compile(r"выбр\w*|выбир\w*|выбер\w*|подход\w*|по карману|что (?:взять|успею|могу позволить)|на что хватит|какой вариант")


def _unit(word):
    if word.startswith("мин"):
        return "мин"
    if word.startswith("бал"):
        return "балл."
    return "тенге" if word=="тенге" else "руб."


def _budget_choice(text,s):
    cap=CAP.search(s)
    if not cap or not CHOOSE.search(s):
        return None
    limit,unit=int(cap[1]),_unit(cap[2])
    options=[]
    for m in ITEM_COST.finditer(text):
        name=m[1].strip(" -—")
        trailing=text[m.end():]
        unknown_unit=not m[3] and re.match(r"\s+(?!а\b|или\b)(?:[а-яёa-z]+|[%$€])",trailing,re.I)
        if (not name or len(name.split())>5 or unknown_unit or re.search(r"бюджет|лимит|предел|максимум|есть только|у нас|у меня|осталось|потратить|\bне\b",name,re.I)
                or m[3] and _unit(_norm(m[3]))!=unit):
            continue
        options.append((name,int(m[2])))
    if len(options)!=2 or len({name.casefold() for name,_ in options})!=2:
        return None
    fits=sorted((cost,name) for name,cost in options if cost<=limit)
    if not fits:
        short=min(cost for _,cost in options)-limit
        return f"Оба варианта выше лимита. Даже при меньшем расходе не хватает {short} {unit}".rstrip(".")+"."
    cost,name=fits[0]
    if len(fits)==2 and fits[1][0]==cost:
        return f"По этому условию оба варианта равны. Каждый требует {cost} из доступных {limit} {unit}".rstrip(".")+"."
    lead=f"В предел укладывается «{name}»" if len(fits)==1 else f"Оба укладываются, но больше запаса даст «{name}»"
    amount=f"Потребуется {cost} из {limit} {unit}".rstrip(".")
    return f"{lead}. {amount}. Остаток — {limit-cost} {unit}".rstrip(".")+"."


