def _activity(text):
    for match in GOAL_HEAD.finditer(text):
        phrase=_slot(text[match.start(1):])
        if not phrase or len(phrase.split())<2:
            continue
        # Timing and money are constraints; avoid embedding them twice.
        phrase=re.split(r"\s+(?:всего )?(?:за|в пределах|всего за)\s+(?:\d+|пять|десять|двадцать|полчаса)\b",phrase,flags=re.I)[0]
        verb=_norm(match[1])
        target=_norm(phrase[len(match[1]):])
        if verb in {"сделать","подготовить"} and not re.search(r"плакат|чертеж|рисунок|макет|текст|памятк|проек[тц]|прототип|открытк|отчет|доклад|слайд|письмо|шаблон|эскиз|объявлен|страниц|иллюстрац",target):
            continue
        if verb=="собрать" and not re.search(r"рюкзак|вещ|чемодан|комплект|багаж|пакет|набор",target):
            continue
        if verb=="проверить" and not re.search(r"текст|ответ|заметк|редакци|письмо|памятк|расчет|список|таблиц|отчет|смет|расч[её]т",target):
            continue
        if verb=="представить" and RELATIVE.search(target):
            continue
        op=next((a for a in OPERATIONS if re.match(r"(?:"+a.verbs+r")",verb)),None)
        if op and len(phrase.split())>1:
            return phrase,op
    return None


