# The infinitive keeps its own object, case and modifiers when embedded
# after «сможете», «не получится» or «чтобы». No noun declension is guessed.
INF = r"[а-яё-]{2,}(?:ть|ти|чь)(?:ся|сь)?"
GOAL_HEAD = re.compile(r"\b(?:хочу|хотим|собираюсь|планирую|поручили|предстоит|нужно|надо|требуется|задача\s*[—–:-]?|как (?:лучше |проще |мне |нам )*)\s*(?:впервые\s+|заранее\s+|самостоятельно\s+|экономно\s+)?("+INF+r")\b", re.I)
STOP_SLOT = re.compile(r"[.!?;:\n«»\"]|,\s*|\s+(?:но|потому что|поскольку|чтобы|а (?:ещё|еще|потом|теперь|затем)|за какое время|и (?:сколько|как|когда))\b",re.I)
PRIVATE_FACT = re.compile(r"^(?:а |ну )?(?:кто|где сейчас|какого цвета|како[йве] (?:цвет|курс)|сколько (?:стоит|весит|лет)|правда ли|как (?:зовут|называется)|что (?:лежит|было написано|я вчера))\b")
UNSAFE_ACTION = re.compile(r"\b(?:уби[вй]\w*|убить|украсть|ограб\w*|избить|ударить|взлом\w*|взры\w*|оруж\w*|наркот\w*|отрав\w*|лекарств\w*|дозиров\w*|таблет\w*|шантаж\w*|порезать себя|парол\w*|банковск\w*|кредит\w*|инвест\w*|уязвимост\w*)\b")
