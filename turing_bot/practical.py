PRIORITY=re.compile(r"(?:важнее(?: всего)?|важна|важен|важно|главное|приоритет|решающее значение имеет)\s*[—–:,-]?\s*(.{2,85})",re.I)


def _preference_with_evidence(text,s):
    priority=PRIORITY.search(s)
    if not priority or not CHOOSE.search(s):
        return None
    selected=[item for item in ATTRIBUTES if re.search(r"\b(?:"+item[0]+")",priority[1])]
    if len(selected)!=1:
        return None
    _,positive,negative,why=selected[0]
    body=text[:priority.start()]
    # Each alternative introduces its own noun phrase and predicate.
    # Adversative subordinate modifiers ("но рвётся") are not new subjects.
    candidates=[]
    for segment in re.split(r"[.;!?]|,\s*а\s+",body,flags=re.I):
        segment=segment.strip(" :—–-")
        m=re.match(r"^(.{1,48}?)(?:\s+[—–-]\s*|\s+|:\s*)(?P<value>"+positive+"|"+negative+r")\b",_norm(segment))
        if not m:
            continue
        name=segment[:m.end(1)].strip(" «»")
        if len(name.split())>4 or re.search(r"\b(?:если|как|выбрать|мне|хочу|но|и|не|может|было бы)\b",name,re.I):
            continue
        candidates.append((name,bool(re.fullmatch(positive,m["value"]))))
    if len(candidates)!=2 or sum(ok for _,ok in candidates)!=1:
        return None
    winner=next(name for name,ok in candidates if ok)
    return f"Из этих двух мой выбор — «{winner}». По твоему описанию, сейчас {why}, и этот вариант лучше отвечает именно этому условию."


def _competing_promises(text,s):
    if not re.search(r"как (?:поступить|быть|выбрать|совместить)|чему отдать|что (?:мне |ты )?(?:сдела|выб|посовет|предлож)|кого (?:предпоч|выб)",s):
        return None
    obligation=re.search(r"\b(?:обеща[лн][аи]?|пообещал[аи]?|договорил(?:ся|ась))\b[^,;.!?]{0,28}?\b("+INF+r"\s+[^.!?;]+)",text,re.I)
    request=re.search(r"\b(?:попросил[аи]?|попросили|просят|просит|пригласил[аи]?|зовут)\b[^,;.!?]{0,24}?\b("+INF+r"\s+[^.!?;]+)",text,re.I)
    if not (obligation and request):
        return None
    old,new=(_slot(m[1]) for m in (obligation,request))
    if not old or not new or old==new or re.search(r"опасност|авари|срочн\w* помощь|здоровь",s):
        return None
    return (f"Я бы сохранил прежнюю договорённость — {old}. Тому, кто просит {new}, "
            "сразу предложил бы другое время. Менять первое обещание стоит по согласию, пока человек успевает перестроиться.")


