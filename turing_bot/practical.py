def _slot(text):
    phrase=STOP_SLOT.split(text,maxsplit=1)[0].strip(" ,—–-")
    if not 2<=len(phrase)<=85 or len(phrase.split())>12:
        return ""
    if re.search(r"\b(?:ты бы|вы бы|подскажи|хотелось бы узнать|что ты|назови)\b",phrase,re.I):
        return ""
    return phrase


def _direct_transfer(text,s):
    """Select a social act, then fill its grammatical object from the utterance."""
    if not re.search(r"как |что (?:ей |ему |им |лучше |мне )?(?:сказать|написать|ответить)|сформулир|подбери|подскажи|напиши|придумай",s):
        return None
    formal=bool(DISTANT.search(s))
    speech_start=re.search(r"\b(?:попросить|попроси|просьбу|напомнить|предложить)\b",s)
    if speech_start:
        after=text[speech_start.end():]
        match=re.search(r"\b("+INF+r")\b",after,re.I)
        if match and match.start()<55 and not re.search(r"[.?!;:]|\b(?:если|когда|чтобы|мне предстоит)\b",after[:match.start()],re.I):
            action=_slot(after[match.start():])
            # Disallow a pronoun-only request and a nested speech command.
            if action and len(action.split())>1 and not re.match(r"(?:сказать|написать) (?:как|почему|что)\b",action,re.I):
                if speech_start[0].startswith("напом"):
                    tail="Буду благодарен, если сообщите, когда будет готово." if formal else "Дай знать, пожалуйста, когда получится."
                    return _quote(f"Небольшое напоминание. Ещё нужно {action}. {tail}")
                if speech_start[0].startswith("предло"):
                    return _quote(f"У меня есть идея. Давайте попробуем {action}." if formal else f"Давай попробуем {action} вместе. Если тебе подойдёт, договоримся о времени.")
                return _quote(f"Здравствуйте! Буду благодарен, если вы сможете {action}." if formal else f"Выручи, пожалуйста. Будет здорово, если сможешь {action}.")
    gratitude=re.search(r"\b(?:поблагодарить|передать благодарность|сказать спасибо)\b[^.!?;]{0,55}?\bза\s+(.+)",text,re.I)
    if gratitude:
        gift=_slot(gratitude[1])
        if gift:
            consequence=_phrase(text,r"\b(?:благодаря этому|теперь)\s+(я (?:могу|успел[аи]?|смог[л]?[аи]?)\s+.+)")
            rest=(" Теперь "+consequence+".") if consequence else " Для меня это много значит."
            return _quote("Спасибо за "+gift+"."+rest)
    refuse=re.search(r"\b(?:сказать|объяснить|написать|сообщить|ответить)\b[^.!?;]{0,42}?(?:,\s*что|\bчто)\s+(?:я\s+)?((?:не смогу|не могу|не готов[а]?|не успеваю)\s+.+)",text,re.I)
    if refuse:
        constraint=_slot(refuse[1])
        if constraint:
            return _quote(constraint[:1].upper()+constraint[1:]+". Предупреждаю заранее, чтобы оставалось время договориться иначе.")
    quote=re.search(r"[«„\"](?:ты\s+)?(?:опять\s+|снова\s+)?не\s+(прислал[аи]?|вернул[аи]?|проверил[аи]?|принес[л]?[аи]?)\s+([^»“\"]{2,65})[»“\"]",text,re.I)
    if quote and re.search(r"мягче|вежлив|спокойн|груб|обид|пере(сказать|формулировать)",s):
        obj=_slot(quote[2])
        verbs={"прис":"прислать","верн":"вернуть","пров":"проверить","прин":"принести"}
        if obj:
            return _quote(f"У меня просьба. Сообщи, пожалуйста, когда сможешь {verbs[_norm(quote[1])[:4]]} {obj}. Мне нужно спланировать остальное.")
    return None


