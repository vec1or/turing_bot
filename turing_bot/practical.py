def _collection(s):
    if not SELECTION.search(s):
        return None
    # Digit mentions alone need not concern the requested selection.
    selection_count=re.search(r"\b(?:выбрать|отобрать|оставить|сократить до|показать|разместить)\s+(?:только\s+|всего\s+|ровно\s+)?(\d{1,3}|одн[ауо]|один|две|два|три|четыре|пять|шесть|семь|восемь|девять|десять)\b",s)
    special=re.search(r"\b(?:из (?:\d+|сотн\w*|десятк\w*|множеств\w*|всех)|коллекци\w*|альбом\w*|подбор\w*|выставк\w*|портфолио|плейлист\w*|антологи\w*|каталог\w*)\b",s)
    if not special and not selection_count:
        return None
    for words,items,group,representative,check in COLLECTIONS:
        if not re.search(r"\b(?:"+words+")",s):
            continue
        if selection_count:
            number=selection_count[1]
            case={"одну":"одной","один":"одного","одно":"одного","две":"двух","два":"двух","три":"трёх","четыре":"четырёх","пять":"пяти","шесть":"шести","семь":"семи","восемь":"восьми","девять":"девяти","десять":"десяти"}
            ending=f"Сократил бы подборку до {case.get(number,number)} и проверил, {check}."
        else:
            ending="В конце проверил бы, "+check+"."
        return f"Сначала я бы сгруппировал {items} по {group}. Затем оставил бы {representative}. {ending}"
    return None


