    if re.search(r"\b(?:перебил\w*|перебива\w*)\b",s) and RELATIVE.search(s):
        if re.search(r"\bя (?:случайно |опять )?перебил\w*\b",s):
            return _quote("Прости, я перебил. Продолжай, пожалуйста, я хочу услышать твою мысль до конца.")
