import unittest

from turing_bot.reasoning import Reasoning


class ReasoningTests(unittest.TestCase):
    def setUp(self):
        self.bot=Reasoning()

    def check(self,cases):
        for q, expected in cases:
            with self.subTest(q=q):
                self.assertEqual(self.bot.answer(q),expected)

    def test_elapsed_and_roles(self):
        self.check([
            ("Автобус отправился в 08:59, а Олег пришёл в 09:02. На сколько минут он опоздал?","3 минуты."),
            ("Я подошёл в 11:44, а читальный зал открывался в 12:03. Сколько минут мне ждать?","19 минут."),
            ("В 19:55 лампа загорелась. В 20:08 она погасла. Сколько минут прошло?","13 минут."),
            ("Какая разница в минутах между 20:12 и 19:59?","13 минут."),
            ("Занятие началось в 16:45 и длилось сорок минут. Во сколько оно закончилось?","В 17:25."),
            ("Поезд отправился в 07:30, я пришёл в 07:15. На сколько минут я опоздал?",None),
            ("В 11:00 окно помыли, в 11:05 я пришёл. На сколько минут я опоздал?",None),
            ("В 19:30 позвонили. Кто позвонил?",None),
        ])

    def test_comparisons_and_indeterminacy(self):
        self.check([
            ("Лика легче Бориса. Борис легче Семёна. Кто самый тяжёлый?","Семён."),
            ("Ирина перед Марком, а Марк перед Евой. Кто стоит первым?","Ирина."),
            ("Тоня выше Аллы. Кира выше Аллы. Кто из них самая высокая?",None),
            ("Ирина старше Лены. Лена выше Оксаны. Кто младше всех?",None),
            ("Мила перед Юлей, а Юля перед Милой. Кто последняя?",None),
            ("Нина выше Юры. Кто выше, Юра или Василиса?",None),
        ])
        self.assertIn("противоречат",self.bot.answer("Мила перед Юлей, а Юля перед Милой. Могут ли оба условия быть верны?"))
        self.assertIn("противоречат",self.bot.answer("Фонарь горит. Фонарь не горит. Есть ли противоречие?"))
        self.assertIsNone(self.bot.answer("Один фонарь горит. Другой фонарь не горит. Есть ли противоречие?"))

    def test_cardinality_changes(self):
        self.check([
            ("В ящике было 9 марок. Добавили две марки, потом убрали 4 марки. Сколько марок осталось?","7."),
            ("В кармане пять жетонов. Один жетон взяли. Сколько жетонов теперь?","4."),
            ("В банке 8 орехов. Взяли три. Сколько их осталось?","5."),
            ("В банке 2 ореха. Забрали 5 орехов. Сколько теперь орехов?",None),
            ("В банке 8 орехов. Убрали две пуговицы. Сколько орехов осталось?",None),
            ("В коробке 10 марок. Убрали 4 марки. Сколько марок убрали?",None),
        ])

    def test_eliminate_only_from_closed_domain(self):
        self.check([
            ("В мешке только белые и синие ленты. Вынутая лента точно не белая. Какого она цвета?","Синего."),
            ("В банке только белые, синие и красные камни. Камень не белый и не синий. Какого цвета камень?","Красного."),
            ("Из входов доступны только северный или восточный. Северный закрыт. Какой вход открыт?","Восточный."),
            ("В мешке белые и синие ленты. Лента не синяя. Какого она цвета?",None),
            ("В мешке только белые и синие ленты. Я вынул ленту. Карандаш не белый. Какого цвета лента?",None),
            ("В мешке только белые и синие ленты. Лента не синяя. Какого цвета коробка?",None),
            ("Из входов доступны только южный или восточный. Южный не был закрыт. Какой вход открыт?",None),
        ])

    def test_inventory_and_bindings(self):
        self.check([
            ("На полке лежали линейка и циркуль. Я убрал циркуль. Что осталось на полке?","Линейка."),
            ("В коробке были лампа и лента. Убрали лампу. Добавили компас. Что осталось?","Лента и компас."),
            ("На полке лежали блокнот и циркуль. Что осталось, когда я убрал карандаш?",None),
            ("В левой сумке хранится зонт, в правой — блокнот. Какую сумку взять, чтобы не промокнуть под дождём?","Зонт в левой сумке."),
            ("У Инги брелок, у Яны пропуск. У кого пропуск?","У Яны."),
            ("Синяя лента лежит в тетради. Где лента?","В тетради."),
            ("В сундуке фонарь. Что лежит в сундуке?","Фонарь."),
            ("В банке жетон, в вазе кольцо. Жетон переложили. Где жетон?",None),
            ("У Оли марка, у Вилы тоже марка. У кого кубик?",None),
        ])

    def test_free_word_order_and_spatial_updates(self):
        self.check([
            ("Перед Сашей стоит Лада. Саша перед Борисом. Кто идёт первым?","Лада."),
            ("В очереди за Ладой стоит Борис. Перед Ниной стоит Лада. Кто идёт впереди всех?","Лада."),
            ("Выше Киры — Вера. Кира выше Ани. Кто выше Киры?","Вера."),
            ("По порядку: дом, шар, кит. Какой объект был вторым?","Шар."),
            ("Фишки слева направо: волк, ёж и рысь. Какая фишка справа?","Рысь."),
            ("В тетради лежал талон. Потом я переложил его в папку. Куда переложили талон?","В папку."),
            ("Лежит медаль на полке. Где медаль?","На полке."),
            ("Сбоку на скамейке лежит жетон. Где находится жетон?","На скамейке."),
            ("Зелёная лента лежала на столе. Открытка была синей. Какого цвета открытка?","Синего."),
            ("Синим был жетон. Какого цвета камень?",None),
            ("Синим был жетон. Какого цвета жетон?","Синего."),
        ])

    def test_quantity_and_schedule_mutations(self):
        self.check([
            ("В четырёх наборах по три кубика. Сколько кубиков во всех наборах?","12."),
            ("В 6 ящиках по восемь мелков. Сколько всего мелков?","48."),
            ("В 6 ящиках по восемь мелков. Сколько всего блокнотов?",None),
            ("Репетиция в девять часов десять минут. Дорога до студии занимает полчаса. Во сколько выйти?","В 08:40."),
            ("Сбор в 15:50. Что покажут часы через четверть часа?","В 16:05."),
            ("Сегодня суббота. Какой день недели будет через три дня?","Вторник."),
            ("Какой день недели будет послезавтра? Сегодня вторник.","Четверг."),
        ])
        self.assertIn("начального количества",self.bot.answer("Из кошелька вынули две монеты. Можно ли определить, сколько монет осталось?"))
        self.assertIn("недостаточно",self.bot.answer("Изначальное число жетонов не указано. Достаточно ли данных для ответа?"))

    def test_short_assertions_match_entity_and_relation(self):
        self.check([
            ("В папке три открытки, в альбоме — семь. Сколько открыток в альбоме?","7."),
            ("В папке три открытки, в альбоме — семь. Сколько открыток всего?","10."),
            ("В папке три открытки, в альбоме — семь. Сколько конвертов в папке?",None),
            ("Вчера Данила подарил Маше фонарь. Кому подарили фонарь?","Маше."),
            ("Нина вручила жетон Павлу. Кто вручил Павлу жетон?","Нина."),
            ("Ира подарила конверт Тане. Кому продали конверт?",None),
            ("У Маши лежали две нити. В трёх корзинах по четыре камня. Сколько камней всего?",None),
        ])


if __name__ == "__main__":
    unittest.main()
