import re
import unittest

from turing_bot.practical import Practical
from turing_bot.situations import Situations


class PracticalTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.model=Practical()

    def useful(self, question, *parts, speech=False):
        result=self.model.answer(question)
        self.assertIsInstance(result,str,question)
        self.assertLessEqual(len(result),300)
        self.assertNotIn("?",result)
        if speech:
            self.assertTrue(result.startswith("«") and result.endswith("»"))
        for part in parts:
            self.assertIn(part,result.casefold(),(question,result))
        return result

    def test_audience_and_speaker_roles(self):
        self.useful("Я поцарапал одолженный у коллеги термос. Как извиниться перед ним?", "прости","ремонт",speech=True)
        self.useful("Друг отдал мне флягу с трещиной. Что ему ответить спокойно?", "флягу с трещиной","поправить",speech=True)
        self.useful("Я перебил сестру, когда она рассказывала о концерте. Что ей написать?", "я перебил","продолжай",speech=True)
        self.useful("Меня перебивает брат. Как сказать ему об этом?", "закончить эту мысль",speech=True)
        self.useful("Сосед включает громкую музыку и мешает сосредоточиться. Как попросить потише?", "чуть тише",speech=True)
        self.useful("Я обещала позвонить папе, но смена затянулась. Что ему написать?", "позвонить","смена затянулась",speech=True)
        out=self.useful("Приятель снова опоздал и не извинился. Что ему написать?", "ждать",speech=True)
        self.assertNotIn("спасибо",out.casefold())

    def test_specific_positive_feedback_and_support(self):
        self.useful("Подруга записала мелодию и ждёт отзыва. Мне понравились переходы. Как её похвалить?", "переходы")
        self.useful("Сестра впервые испекла булочки. Я так радуюсь за неё!", "она испекла булочки")
        self.useful("Я наконец собрал работающую лампу. Ура!", "поздравляю","лампу")
        self.useful("Приятель проиграл в финале и переживает. Что ему написать?", "выслушать",speech=True)

    def test_scarcity_and_collections(self):
        self.useful("На нашей репетиции двум участникам нужен один микрофон. Как справедливо поделить?", "жребий")
        self.useful("На всех один пирог. Как честно разделить между ребятами?", "равные части")
        self.useful("Как выбрать три мелодии из десятка для плейлиста?", "темпу","до трёх","переходы")
        self.useful("Нужно выбрать пять эскизов для выставки. С чего начать?", "технике","до пяти")

    def test_logistics_and_measurable_goals(self):
        self.useful("Мне неудобно доставать пропуск одной рукой. Как упростить это заранее?", "закрывающийся карман","петлю")
        self.useful("Осталась половина яблока. Как не забыть про неё к завтраку?", "завтраку")
        self.useful("Как подписать коробки с материалами, чтобы потом быстро найти нужное?", "содержимое","не открывая")
        self.useful("Как согласовать общее время созвона с коллегами?", "интервалов")
        self.useful("Я провожу квест для новичков. Как проверить, посильны ли задания?", "пробный пример","засёк")
        self.useful("Какая маленькая цель подойдёт, если хочу играть на гитаре?", "в ровном темпе","запишу")
        self.useful("На докладе погас проектор. Как продолжить выступление?", "главную мысль","без слайда")

    def test_abstentions_and_count_scope(self):
        for q in ("Какого цвета неизвестная фотография?", "Когда в следующий раз будет викторина?",
                  "Нужно выбрать одного из двух неизвестных людей. Как зовут первого?",
                  "Приведи три разных фразы, чтобы похвалить выступление.",
                  "Сестра впервые не смогла сыграть мелодию. Я не горжусь тем, как повёл себя.",
                  "Мой коллега вернул чайник. Сколько лет человеку, который его сделал?",
                  "Какая температура у лимона на моей полке?", "Мне прислали несколько идей. Кто автор третьей?"):
            with self.subTest(q=q):
                self.assertIsNone(self.model.answer(q))
        old=Situations()
        self.assertIsNone(old.answer("Я поставил на полку две вещи. Что осталось после того, как одну забрали?"))
        self.assertIsNotNone(old.answer("Дай три совета по подготовке к экзамену."))

    def test_infinitive_and_role_transfer(self):
        self.useful("Как попросить учителя отложить репетицию на понедельник?", "вы сможете","отложить репетицию на понедельник",speech=True)
        self.useful("Как попросить дядю привезти старую мандолину на дачу?", "сможешь привезти","мандолину на дачу",speech=True)
        self.useful("Как поблагодарить мастера за починку защёлки?", "спасибо за починку защёлки",speech=True)
        self.useful("Как объяснить коллеге, что не успеваю оформить витрину к обеду?", "не успеваю оформить витрину к обеду",speech=True)
        self.useful("Как сказать мягче «Ты снова не прислал чертёж»?", "прислать чертёж",speech=True)
        self.useful("Я обещал покормить рыб, но меня попросили перенести стеллаж. Как поступить?", "покормить рыб","перенести стеллаж","другое время")

    def test_procedure_with_time_or_money_limit(self):
        out=self.useful("Мне поручили рассортировать значки. Осталось пятнадцать минут. С чего начать?", "рассортировать значки","группировки","проверил")
        self.assertEqual(sum(map(int,re.findall(r"(\d+) мин —",out))),15)
        self.useful("Хочу вычитать описание спектакля за полчаса. Как распорядиться временем?", "вычитать описание","правки")
        self.useful("Нужно впервые упаковать три свистка. С чего лучше начать?", "упаковать три свистка","со списком")
        self.useful("Как устроить обмен открытками почти бесплатно?", "обмен открытками","участники","покупок")
        self.useful("Хочу смастерить подставку без покупок. С чего бы ты начал?", "подставку","пробный вариант")

    def test_choice_uses_only_stated_evidence(self):
        self.useful("Бюджет — 400 тенге. Трубка стоит 380, а муфта — 450. Что выбрать?", "трубка","20 тенге")
        self.useful("У нас всего 27 минут. Прогон занимает 22 минуты, монтаж — 35 минут. Что выбрать?", "прогон","5 мин")
        self.useful("Лимит 32 балла. Овал стоит 36, а круг — 39. На что хватит?", "не хватает 4")
        self.useful("Первая опора прочная, а вторая хрупкая. Как выбрать, если приоритет — прочность?", "первая опора","прочности")
        self.useful("Большой мотор шумный. Маленький мотор тихий. Что выбрать, если важна тишина?", "маленький мотор")
        self.useful("Стоит ли публично поправить коллегу, если в его расчёте ошибка?", "наедине","при всех")

    def test_prevents_inventing_constraints_or_unsafe_recommendations(self):
        for q in ("Лимит — 500 рублей. Эскиз стоит 20 евро, а открытка — 350 рублей. Что выбрать?",
                  "Одно приспособление не лёгкое, а другое тяжёлое. Что выбрать, если главное — вес?",
                  "Синяя и зелёная кассеты. Что выбрать, если главное — прочность?",
                  "Мне надо проверить самочувствие за двадцать минут. Как узнать точный диагноз?",
                  "Как вежливо попросить знакомого прислать пароль другого человека?",
                  "Мне нужно подготовить ужин за десять минут. Как с ним управиться?",
                  "Нужно собрать команду за пять минут. Как разложить всё по карманам?"):
            with self.subTest(q=q):
                self.assertIsNone(self.model.answer(q))


if __name__=="__main__":
    unittest.main()
